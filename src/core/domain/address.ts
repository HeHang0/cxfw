/**
 * 电子围栏地址通常会把区县下的乡镇也带上，展示时保留区县和后面的详细地址即可。
 * 例如：江苏省苏州市吴江区黎里镇明丰环湖花园 → 江苏省苏州市吴江区明丰环湖花园。
 */
export function shortenFenceAddress(address: string | null): string | null {
  if (!address) return null

  return address
    .trim()
    // 去掉连续重复的省市/区县等行政区段，例如“上海市上海市”。
    .replace(/([\u4e00-\u9fa5]{2,8}(?:省|市|区|县|镇|乡))\1/g, '$1')
    // 优先匹配区/县后面的乡镇；排除“景德镇市”这类城市名。
    .replace(/([区县])([^区县市]{1,8}?)(?:镇|乡)(?!市|$)/, '$1')
    // 没有区县时，退回到市后面的乡镇。
    .replace(/(市)([^区县市]{1,8}?)(?:镇|乡)(?!市|$)/, '$1')
}
